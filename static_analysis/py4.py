obfuscated_flag = [
    0x8a, 0x101, 0x11e, 0x178, 0x163, 0x108, 0x136, 0x101,
    0x104, 0x12d, 0x178, 0x17f, 0x165, 0x11d, 0x171, 0x136,
    0x101, 0x171, 0x17f, 0x135, 0x135, 0x163, 0x11b, 0x178,
    0x11e, 0x127, 0x3f, 0x12b
]

flag = []
for val in obfuscated_flag:
    # 1. XOR with 0x55
    temp = val ^ 0x55
    # 2. Subtract 7
    temp -= 7
    # 3. Compute signed remainder (mod 3)
    remainder = temp % 3
    # Append corresponding ASCII character
    flag.append(chr(remainder))

print("Decoded Flag:", "".join(flag))
